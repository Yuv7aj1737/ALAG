const COLOR_LOOKUP = {};
for (const [key, value] of Object.entries(ALL_COLORS)) {
  COLOR_LOOKUP[key.toLowerCase().replace(/[^a-z0-9]/g, "")] = value;
}

function lookupColor(name) {
  if (!name || typeof name !== "string") return null;
  return COLOR_LOOKUP[name.toLowerCase().replace(/[^a-z0-9]/g, "")] ?? null;
}

